#ifndef LIBMCB_TARGET_GNU_ASM_VALUE_KIND_H
#define LIBMCB_TARGET_GNU_ASM_VALUE_KIND_H

#define IS_INT(VALUE_KIND) \
	(IS_INT_IMM(VALUE_KIND) || \
	 IS_INT_MEM(VALUE_KIND) || \
	 IS_INT_REG(VALUE_KIND))
#define IS_UINT(VALUE_KIND) \
	(IS_INT_IMM(VALUE_KIND) || \
	 IS_INT_MEM(VALUE_KIND) || \
	 IS_INT_REG(VALUE_KIND))

#define IS_INT_DATA(VALUE_KIND) \
	((VALUE_KIND) >= I8_DATA_VALUE && \
	 (VALUE_KIND) <= I64_DATA_VALUE)
#define IS_INT_IMM(VALUE_KIND) \
	((VALUE_KIND) >= I8_IMM_VALUE && \
	 (VALUE_KIND) <= I64_IMM_VALUE)
#define IS_INT_MEM(VALUE_KIND) \
	((VALUE_KIND) >= I8_MEM_VALUE && \
	 (VALUE_KIND) <= I64_MEM_VALUE)
#define IS_INT_REG(VALUE_KIND) \
	((VALUE_KIND) >= I8_REG_VALUE && \
	 (VALUE_KIND) <= I64_REG_VALUE)

#define IS_UINT_DATA(VALUE_KIND) \
	((VALUE_KIND) >= U8_DATA_VALUE && \
	 (VALUE_KIND) <= U64_DATA_VALUE)
#define IS_UINT_IMM(VALUE_KIND) \
	((VALUE_KIND) >= U8_IMM_VALUE && \
	 (VALUE_KIND) <= U64_IMM_VALUE)
#define IS_UINT_MEM(VALUE_KIND) \
	((VALUE_KIND) >= U8_MEM_VALUE && \
	 (VALUE_KIND) <= U64_MEM_VALUE)
#define IS_UINT_REG(VALUE_KIND) \
	((VALUE_KIND) >= U8_REG_VALUE && \
	 (VALUE_KIND) <= U64_REG_VALUE)

#define IS_DATA(VALUE_KIND) \
	(IS_INT_DATA(VALUE_KIND) || IS_UINT_DATA(VALUE_KIND))
#define IS_IMM(VALUE_KIND) \
	(IS_INT_IMM(VALUE_KIND) || IS_UINT_IMM(VALUE_KIND))
#define IS_MEM(VALUE_KIND) \
	(IS_INT_MEM(VALUE_KIND) || IS_UINT_MEM(VALUE_KIND))
#define IS_REG(VALUE_KIND) \
	(IS_INT_REG(VALUE_KIND) || IS_UINT_REG(VALUE_KIND))

#define CASE_I8_VALUE \
	case I8_DATA_VALUE: case I8_IMM_VALUE: \
	case I8_MEM_VALUE:  case I8_REG_VALUE
#define CASE_I16_VALUE \
	case I16_DATA_VALUE: case I16_IMM_VALUE: \
	case I16_MEM_VALUE:  case I16_REG_VALUE
#define CASE_I32_VALUE \
	case I32_DATA_VALUE: case I32_IMM_VALUE: \
	case I32_MEM_VALUE:  case I32_REG_VALUE
#define CASE_I64_VALUE \
	case I64_DATA_VALUE: case I64_IMM_VALUE: \
	case I64_MEM_VALUE:  case I64_REG_VALUE

#define CASE_U8_VALUE \
	case U8_DATA_VALUE: case U8_IMM_VALUE: \
	case U8_MEM_VALUE:  case U8_REG_VALUE
#define CASE_U16_VALUE \
	case U16_DATA_VALUE: case U16_IMM_VALUE: \
	case U16_MEM_VALUE:  case U16_REG_VALUE
#define CASE_U32_VALUE \
	case U32_DATA_VALUE: case U32_IMM_VALUE: \
	case U32_MEM_VALUE:  case U32_REG_VALUE
#define CASE_U64_VALUE \
	case U64_DATA_VALUE: case U64_IMM_VALUE: \
	case U64_MEM_VALUE:  case U64_REG_VALUE

#define CASE_DATA_VALUE \
	case I8_DATA_VALUE:  case I16_DATA_VALUE: \
	case I32_DATA_VALUE: case I64_DATA_VALUE: \
	case U8_DATA_VALUE:  case U16_DATA_VALUE: \
	case U32_DATA_VALUE: case U64_DATA_VALUE
#define CASE_IMM_VALUE \
	case I8_IMM_VALUE:  case I16_IMM_VALUE: \
	case I32_IMM_VALUE: case I64_IMM_VALUE: \
	case U8_IMM_VALUE:  case U16_IMM_VALUE: \
	case U32_IMM_VALUE: case U64_IMM_VALUE
#define CASE_MEM_VALUE \
	case I8_MEM_VALUE:  case I16_MEM_VALUE: \
	case I32_MEM_VALUE: case I64_MEM_VALUE: \
	case U8_MEM_VALUE:  case U16_MEM_VALUE: \
	case U32_MEM_VALUE: case U64_MEM_VALUE
#define CASE_REG_VALUE \
	case I8_REG_VALUE:  case I16_REG_VALUE: \
	case I32_REG_VALUE: case I64_REG_VALUE: \
	case U8_REG_VALUE:  case U16_REG_VALUE: \
	case U32_REG_VALUE: case U64_REG_VALUE

enum GNU_ASM_VALUE_KIND {
	UNKOWN_VALUE,

	I8_DATA_VALUE, I16_DATA_VALUE, I32_DATA_VALUE, I64_DATA_VALUE,
	U8_DATA_VALUE, U16_DATA_VALUE, U32_DATA_VALUE, U64_DATA_VALUE,

	I8_IMM_VALUE, I16_IMM_VALUE, I32_IMM_VALUE, I64_IMM_VALUE,
	U8_IMM_VALUE, U16_IMM_VALUE, U32_IMM_VALUE, U64_IMM_VALUE,

	I8_MEM_VALUE, I16_MEM_VALUE, I32_MEM_VALUE, I64_MEM_VALUE,
	U8_MEM_VALUE, U16_MEM_VALUE, U32_MEM_VALUE, U64_MEM_VALUE,

	I8_REG_VALUE, I16_REG_VALUE, I32_REG_VALUE, I64_REG_VALUE,
	U8_REG_VALUE, U16_REG_VALUE, U32_REG_VALUE, U64_REG_VALUE,

	CMP_RESULT_VALUE,
	STRUCT_VALUE
};

#endif
